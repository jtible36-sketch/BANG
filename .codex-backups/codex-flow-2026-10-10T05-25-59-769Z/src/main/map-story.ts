import { isMapMaster, masterStageDirection, resolveMasterPrompt } from '@shared/master-prompts'
import { MAP_STYLE_LOCK, MAP_VISUAL_DIRECTION, mapStyleLock } from '@shared/map-animation'
import { subjectNicheDirection } from '@shared/niches'
import { buildFlowVideoPrompt } from '@shared/external-prompts'
import type { ProjectBundle } from '@shared/types'
import { applyVisuals, clipsOf, getBundle, getProject, type SceneVisual } from './repo'
import { generateJson } from './services/llm'
import { getSettings } from './settings'

const MAP_VISUAL_SCHEMA = {
  type: 'object', additionalProperties: false, properties: {
    scenes: { type: 'array', items: { type: 'object', additionalProperties: false, properties: {
      scene: { type: 'integer', description: 'Exact scene number supplied by the app.' },
      image: { type: 'string', description: 'Scene 1 ONLY: a wide continental daylight starting frame, target border just beginning. Every subsequent scene must return empty string: it uses the preceding video final frame, not a generated image.' },
      startState: { type: 'string', description: 'Exact initial geographic view, framing, overlays/icons/lighting/palette. For every scene after 1, copy the previous endState VERBATIM; never paraphrase it.' },
      camera: { type: 'string', description: 'English: one primary smooth camera move plus subtle drift. Scene 1 wide continental view smoothly plunges into target; no cuts or whip pans.' },
      beat0To2: { type: 'string', description: 'English action from 0-2 seconds, continuing exactly from startState.' },
      beat2To5: { type: 'string', description: 'English action from 2-5 seconds, same uninterrupted geography/view.' },
      beat5To8: { type: 'string', description: 'English action from 5-8 seconds ending at endState.' },
      endState: { type: 'string', description: 'Precise final frame: real geography, camera/framing/scale, every neon overlay/icon and color, terrain/time/light. Single paragraph; reused exactly as next startState.' },
      avoid: { type: 'string', description: 'Specific geographic distortion/errors to avoid plus no cuts, text/logos/flags, morphing/flicker/shake, dark lighting or unsupported border assertions.' },
      sfx: { type: 'string', description: 'Timed editing cues only: bass whoosh on plunge, scanner on border/line reveal, radar beep on pin, restrained twist impact. Audio is added separately, not generated by this planner.' },
      music: { type: 'string', description: 'Low atmospheric drone editing guidance, ducked under narrator and building toward payoff. No claim to have generated audio.' }
    }, required: ['scene', 'image', 'startState', 'camera', 'beat0To2', 'beat2To5', 'beat5To8', 'endState', 'avoid', 'sfx', 'music'] } }
  }, required: ['scenes']
}

type MapScene = { scene: number; image: string; startState: string; camera: string; beat0To2: string; beat2To5: string; beat5To8: string; endState: string; avoid: string; sfx: string; music: string }
const text = (value: unknown): string => typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : ''

function context(projectId: string): string {
  const project = getProject(projectId)
  return JSON.stringify([project.synopsis, project.subjectNiche, project.styleId, project.skillId, project.skillVariant, project.language,
    project.aspectRatio, resolveMasterPrompt(project), clipsOf(projectId).map(clip => [clip.id, clip.story, clip.narration, clip.characterIds, clip.visualPrompt, clip.videoPrompt])])
}

/** Plan the whole continuous chain together; partial replanning could invalidate later START STATEs. */
export async function generateMapVisuals(projectId: string, signal?: AbortSignal): Promise<ProjectBundle> {
  signal?.throwIfAborted()
  const project = getProject(projectId)
  if (!isMapMaster(project)) throw new Error('Master Map Animation belum dipilih.')
  const clips = clipsOf(projectId)
  if (!clips.length || clips.some(clip => !clip.narration.trim())) throw new Error('Isi narasi semua adegan sebelum menyusun rangkaian peta.')
  if (clips.length > 32) throw new Error('Rangkaian Map Animation maksimal 32 adegan dalam satu perencanaan. Bagi cerita panjang agar kesinambungan frame bisa ditinjau.')
  const captured = context(projectId)
  const canonicalDirection = MAP_VISUAL_DIRECTION.replaceAll(MAP_STYLE_LOCK, mapStyleLock(project.aspectRatio))
  const masterDirection = masterStageDirection(project, 'visual')
  const result = await generateJson<{ scenes?: MapScene[] }>({
    system: [masterDirection.includes(canonicalDirection) ? '' : canonicalDirection, masterDirection, subjectNicheDirection(project.subjectNiche),
      'The reviewed narration is FINAL. Design a continuous map chain, not independent scenes or a character story. Keep real geography neutrally phrased, daylight, fixed neon semantics and one consistent icon design. Never invent precise coordinates, borders, numbers or discoveries absent from supported story material.',
      'Return structured scene data only. Scene 1 alone has image text. Later image fields MUST be empty. Copy each previous endState exactly into the next startState. No cast, avatars or character sheets. SFX/music fields are editing cues, not audio generation.'
    ].filter(Boolean).join('\n\n'),
    prompt: [`Niche: ${project.subjectNiche || 'Follow the reviewed geographic story'}.`, `Format: ${project.aspectRatio}; source clips 8 seconds each, regardless of edited narration duration.`,
      `Story: ${project.synopsis}`, `Return exactly ${clips.length} chronological scenes numbered 1-${clips.length}, in this order.`,
      clips.map((clip, index) => `Scene ${index + 1}: ${clip.title}\nReviewed story: ${clip.story}\nExact narration: ${clip.narration}`).join('\n\n')
    ].join('\n\n'), schema: MAP_VISUAL_SCHEMA, name: 'map_visuals', signal, timeoutKind: 'visual',
    ...(getSettings().visualPlannerSource === 'codex' ? { source: 'codex', channel: 'visual' } as const : {})
  })
  signal?.throwIfAborted()
  if (!Array.isArray(result?.scenes) || result.scenes.length !== clips.length) throw new Error('Rangkaian peta belum lengkap. Visual sebelumnya tetap tersimpan; susun ulang visual.')
  const updates: SceneVisual[] = []
  let previousEnd = ''
  for (let index = 0; index < clips.length; index++) {
    const scene = result.scenes[index]
    if (!scene || Number(scene.scene) !== index + 1 || ['startState', 'camera', 'beat0To2', 'beat2To5', 'beat5To8', 'endState', 'avoid', 'sfx', 'music'].some(key => !text(scene[key as keyof MapScene]))) {
      throw new Error(`Rencana peta adegan ${index + 1} belum lengkap. Visual sebelumnya tetap tersimpan.`)
    }
    if (index === 0 ? !text(scene.image) : text(scene.image)) throw new Error('Hanya adegan pertama boleh memiliki prompt gambar. Adegan lanjutan memakai frame akhir video sebelumnya; visual lama tetap tersimpan.')
    if (index > 0 && text(scene.startState) !== previousEnd) throw new Error(`Keadaan awal adegan ${index + 1} tidak sama dengan akhir adegan sebelumnya. Susun ulang rangkaian; visual lama tetap tersimpan.`)
    previousEnd = text(scene.endState)
    const clip = clips[index]
    const videoPrompt = [mapStyleLock(project.aspectRatio), `START FRAME: ${index === 0 ? 'SCENE_IMAGE' : 'PREVIOUS_VIDEO'}`,
      `START STATE: ${text(scene.startState)}`, `CAMERA: ${text(scene.camera)}`,
      `TIMELINE: 0-2s ${text(scene.beat0To2)} / 2-5s ${text(scene.beat2To5)} / 5-8s ${text(scene.beat5To8)}`,
      `END STATE: ${previousEnd}`, `AVOID: ${text(scene.avoid)}`,
      `AUDIO PLAN:\nVOICEOVER (${project.language}): ${clip.narration}\nSFX (editing cues): ${text(scene.sfx)}\nMUSIC (editing guidance): ${text(scene.music)}`
    ].join('\n\n')
    updates.push({ clipId: clip.id, visualPrompt: index === 0 ? text(scene.image) : `Previous video final-frame reference.\n${text(scene.startState)}`,
      videoPrompt, characterNames: [], cameraPreset: index === 0 ? 'zoomin' : 'static', motionStrength: 'halus', transition: 'cut' })
  }
  // The same validator used by the copy buttons also checks the complete saved chain before commit.
  const planned = clips.map((clip, index) => ({ ...clip, videoPrompt: updates[index].videoPrompt }))
  for (const clip of planned) buildFlowVideoPrompt(project, clip, planned)
  if (captured !== context(projectId)) throw new Error('Niche, naskah, format, atau rangkaian peta berubah selama penyusunan. Visual lama tetap tersimpan; susun lagi.')
  signal?.throwIfAborted()
  applyVisuals(projectId, [], updates)
  return getBundle(projectId)
}
